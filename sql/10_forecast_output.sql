CREATE TABLE IF NOT EXISTS FTB.GOLD.FORECAST_OUTPUT (
    GEO_LEVEL     VARCHAR      NOT NULL,   -- COUNTY | ZIP | TRACT
    GEO_ID        VARCHAR      NOT NULL,   -- FIPS or ZIP as text
    MONTH         DATE         NOT NULL,
    MEASURE       VARCHAR      NOT NULL,
    SCENARIO      VARCHAR      NOT NULL DEFAULT 'BASELINE',
    IS_FORECAST   BOOLEAN      NOT NULL,
    VALUE         NUMBER(18,4),
    LOWER         NUMBER(18,4),
    UPPER         NUMBER(18,4),
    MODEL_VERSION VARCHAR,
    RUN_TS        TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Latest run per key, for Power BI
CREATE OR REPLACE VIEW FTB.GOLD.V_FORECAST_LATEST AS
SELECT *
FROM FTB.GOLD.FORECAST_OUTPUT
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY GEO_LEVEL, GEO_ID, MONTH, MEASURE, SCENARIO
    ORDER BY RUN_TS DESC
) = 1;

